// ── Helper functions ──────────────────────────────────
function getProductsByCategory(categoryId) {
    if (!categoryId || categoryId === "all") return products;
    return products.filter(p => p.category === categoryId);
}

function searchProducts(query) {
    const q = query.toLowerCase();
    return products.filter(p =>
        p.name.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q)
    );
}

function sortProducts(list, method) {
    const copy = [...list];
    if (method === "price-low") return copy.sort((a, b) => a.price - b.price);
    if (method === "price-high") return copy.sort((a, b) => b.price - a.price);
    if (method === "rating") return copy.sort((a, b) => b.rating - a.rating);
    if (method === "reviews") return copy.sort((a, b) => b.reviews - a.reviews);
    return copy;
}